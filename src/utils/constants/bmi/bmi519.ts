export const bmi519 = (
  value: number,
  totalMonthAge: number,
  gender: string,
) => {
  const _3D = gender === 'nam' ? age3DMale : age3DFemale;
  const _2D = gender === 'nam' ? age2DMale : age2DFemale;
  const _2SD = gender === 'nam' ? age2SDMale : age2SDFemale;
  const _1SD = gender === 'nam' ? age1SDMale : age1SDFemale;
  const _3SD = gender === 'nam' ? age3SDMale : age3SDFemale;

  // Theo như mô tả từ file document. Từ 5 tuổi sẽ bắt đầu từ tháng 61
  // Cần -61 để phù hợp với logic sử dụng index hiện tại
  const calMonthAge = totalMonthAge - 61;
  if (value < _3D[calMonthAge] || value < _3D[0]) {
    return 1;
  } else if (value >= _3D[calMonthAge] && value < _2D[calMonthAge]) {
    return 2;
  } else if (value >= _2D[calMonthAge] && value <= _1SD[calMonthAge]) {
    return 3;
  } else if (value > _1SD[calMonthAge] && value <= _2SD[calMonthAge]) {
    return 4;
  } else if (value > _2SD[calMonthAge] || value > _2SD[_2SD.length - 1]) {
    return 5;
  }
  return 0;
};

